    public static string Language(string language) => language == "auto" ? CultureInfo.CurrentUICulture.TwoLetterISOLanguageName : language;
    public static string T(string key, string language = "auto") => Texts.TryGetValue(key, out var values) ? values[Language(language) switch { "ko" => 0, "ja" => 2, _ => 1 }] : key;
    public static string PeriodKey(ContentPeriod period) => period switch { ContentPeriod.Today => "period.today", ContentPeriod.TwoDays => "period.two", _ => "period.week" };
    public static string Status(Snapshot s, DateTimeOffset now, TimeZoneInfo zone)
    {
        if (s.Status == CollectionStatus.Disconnected) return T("disconnected", s.Settings.Language);
        if (s.Status == CollectionStatus.Stopped || now - s.Heartbeat >= TimeSpan.FromSeconds(90)) return T("stopped", s.Settings.Language);
        if (s.IsCollecting) return T("loading", s.Settings.Language);
        return T(s.Status == CollectionStatus.Ready ? (s.Fresh(now, zone) ? "checked" : "stale") : s.Status.ToString().ToLowerInvariant(), s.Settings.Language);
    }
